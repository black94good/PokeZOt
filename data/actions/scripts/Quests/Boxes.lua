function onUse(cid, item, frompos, item2, topos)

	local Boxs = Boxs[item.itemid]                                 
	if not Boxs then return true end
	local pokemon = Boxs.pokemons[math.random(#Boxs.pokemons)]
	if not pokes[pokemon] then return true end  
	
	if Boxs.boost ~= nill then
		boost = Boxs.boost
	else
		boost = nil
	end

	doPlayerSendTextMessage(cid, 27, "You opened a pokemon prize box +"..item.itemid - (11637).."!")
	doPlayerSendTextMessage(cid, 27, "The prize pokemon was a "..pokemon..", congratulations!")
	doSendMagicEffect(getThingPos(cid), 29)
	
	addPokeToPlayer(cid, pokemon, boost, nil, btype)     --alterado v1.9                                                 
	doRemoveItem(item.uid, 1)
	doPlayerSave(cid)
	
	return true
end